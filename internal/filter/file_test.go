func TestShouldSkip_GeneratedFile(t *testing.T) {
	generatedPatch := `@@ -0,0 +1,5 @@
+// Code generated by protoc-gen-go. DO NOT EDIT.
+package pb
+
+type Foo struct{}
`
	if !ShouldSkip("pb/foo.pb.go", generatedPatch, nil) {
		t.Error("expected generated file to be skipped")
	}
}

