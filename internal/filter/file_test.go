func TestMeetsSeverityThreshold(t *testing.T) {
	cases := []struct {
		comment string
		min     string
		want    bool
	}{
		{"error", "suggestion", true},
		{"warning", "suggestion", true},
		{"suggestion", "suggestion", true},
		{"error", "warning", true},
		{"warning", "warning", true},
		{"suggestion", "warning", false},
		{"error", "error", true},
		{"warning", "error", false},
		{"suggestion", "error", false},
	}
	for _, tc := range cases {
		got := MeetsSeverityThreshold(tc.comment, tc.min)
		if got != tc.want {
			t.Errorf("MeetsSeverityThreshold(%q, %q) = %v, want %v",
				tc.comment, tc.min, got, tc.want)
		}
	}
}

func TestIsCategoryEnabled(t *testing.T) {
	cfg := &RepoConfig{
		Categories: []string{"bug", "security"},
	}

	if !IsCategoryEnabled("bug", cfg) {
		t.Error("bug should be enabled")
	}
	if !IsCategoryEnabled("security", cfg) {
		t.Error("security should be enabled")
	}
	if IsCategoryEnabled("performance", cfg) {
		t.Error("performance should NOT be enabled")
	}
}

func TestIsCategoryEnabled_EmptyList(t *testing.T) {
	cfg := &RepoConfig{Categories: []string{}}
	// Empty list means all categories are enabled.
	if !IsCategoryEnabled("bug", cfg) {
		t.Error("with empty category list, all categories should be enabled")
	}
	if !IsCategoryEnabled("performance", cfg) {
		t.Error("with empty category list, all categories should be enabled")
	}
}

func TestFilterFiles(t *testing.T) {
	files := []FileEntry{
		{Filename: "main.go", Patch: "+code"},
		{Filename: "go.sum", Patch: "+hash"},
		{Filename: "vendor/lib/lib.go", Patch: "+code"},
		{Filename: "internal/handler.go", Patch: "+code"},
		{Filename: "logo.png", Patch: ""},
	}

	result := FilterFiles(files, nil)

	if len(result) != 2 {
		t.Fatalf("expected 2 reviewable files, got %d", len(result))
	}
	if result[0].Filename != "main.go" {
		t.Errorf("expected main.go, got %s", result[0].Filename)
	}
	if result[1].Filename != "internal/handler.go" {
		t.Errorf("expected internal/handler.go, got %s", result[1].Filename)
	}
}
